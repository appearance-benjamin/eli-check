const LANG_KEY = "elicheck.lang";

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "nl") return saved;
  } catch {}
  return (navigator.language || "en").toLowerCase().startsWith("nl") ? "nl" : "en";
}

let lang = detectLang();

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {}
  document.documentElement.lang = next;
}

/** UI string by key, with {placeholder} substitution. */
export function t(key, vars = {}) {
  const value = key.split(".").reduce((o, k) => (o ? o[k] : undefined), UI[lang]) ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

/** Pick the current language from an {en, nl} object (or return a plain string as-is). */
export function L(text) {
  if (text == null) return "";
  if (typeof text === "string") return text;
  return text[lang] ?? text.en;
}

export function money(amount, { decimals = 0 } = {}) {
  return new Intl.NumberFormat(lang === "nl" ? "nl-NL" : "en-IE", {
    style: "currency",
    currency: "EUR",
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(amount);
}

export function number(value) {
  return new Intl.NumberFormat(lang === "nl" ? "nl-NL" : "en-IE").format(value);
}
