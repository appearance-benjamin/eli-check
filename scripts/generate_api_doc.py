"""Write docs/api.md: every input and output variable with entity, period and label.

    python scripts/generate_api_doc.py
"""

from pathlib import Path

from openfisca_nl import CountryTaxBenefitSystem

ROOT = Path(__file__).resolve().parent.parent

GROUPS = [
    ("Zorgtoeslag", lambda n: n.startswith("zorgtoeslag")),
    ("Huurtoeslag", lambda n: n.startswith("huurtoeslag")),
    ("Kindgebonden budget", lambda n: n.startswith("kindgebonden_budget")),
    ("Kinderbijslag", lambda n: n == "kinderbijslag"),
    (
        "Studiefinanciering (DUO)",
        lambda n: any(k in n for k in ("studiefinanciering", "beurs", "lening", "collegegeld", "reisproduct", "scholieren", "migrerend", "ouderbijdrage", "arbeidsinkomen_per")),
    ),
    ("Bijstand", lambda n: n.startswith("bijstand") or n in {"sociaal_minimum", "netto_huishoudinkomen_per_maand", "inkomen_percentage_bijstandsnorm"}),
    ("Income tax", lambda n: n in {"inkomstenbelasting", "geschatte_ingehouden_loonheffing", "belastingteruggave", "netto_jaarinkomen"}),
    ("Maastricht", lambda n: n.startswith("maastricht") or n.startswith("kwijtschelding")),
]


def kind(variable):
    if getattr(variable, "possible_values", None) is not None:
        return "enum: " + " / ".join(variable.possible_values._member_names_)
    if variable.value_type is bool:
        return "bool"
    if variable.unit == "currency-EUR":
        return "€"
    return variable.value_type.__name__


def main():
    tbs = CountryTaxBenefitSystem()
    variables = tbs.variables
    lines = [
        "# Eli Check API reference",
        "",
        "Generated by `scripts/generate_api_doc.py` — do not edit by hand.",
        "",
        'Periods in a situation: MONTH = `"2026-10"`, YEAR = `"2026"`, ETERNITY = `"ETERNITY"`.',
        "Convention: `<scheme>_voorwaarde_<naam>` is a boolean (True = condition met) with the same entity and period as the scheme.",
        "",
        "## Inputs",
        "",
        "| variable | entity | period | type | default | meaning |",
        "|---|---|---|---|---|---|",
    ]
    inputs = sorted(name for name, v in variables.items() if not v.formulas)
    for name in inputs:
        v = variables[name]
        default = getattr(v.default_value, "name", v.default_value)
        lines.append(f"| `{name}` | {v.entity.key} | {v.definition_period} | {kind(v)} | {default} | {v.label} |")

    done = set(inputs)
    for title, belongs in GROUPS:
        names = [name for name in variables if name not in done and belongs(name)]
        done.update(names)
        lines += ["", f"## {title}", "", "| variable | entity | period | type | meaning |", "|---|---|---|---|---|"]
        for name in names:
            v = variables[name]
            lines.append(f"| `{name}` | {v.entity.key} | {v.definition_period} | {kind(v)} | {v.label} |")

    rest = sorted(name for name in variables if name not in done)
    lines += ["", "## Helpers", "", "| variable | entity | period | type | meaning |", "|---|---|---|---|---|"]
    for name in rest:
        v = variables[name]
        lines.append(f"| `{name}` | {v.entity.key} | {v.definition_period} | {kind(v)} | {v.label} |")

    (ROOT / "docs" / "api.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(variables)} variables ({len(inputs)} inputs) written to docs/api.md")


if __name__ == "__main__":
    main()
